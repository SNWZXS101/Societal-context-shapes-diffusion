% ===== 内部：加深算法 =====
function C2 = smf_darken(C, d)
% 向黑色线性混合 d（0~0.3 建议）。同时对极浅色做最小阈，避免过白发虚。
C2 = (1-d).*C;                                % 主体：整体压暗
% 对接近白色的颜色，先拉到 0.90，再压暗，避免“几乎白”的一列显得发虚
tooLight = mean(C,2) > 0.92;
C2(tooLight,:) = max(0.90, 1-d).*C(tooLight,:);  % 轻度下压亮度，但保留色相
% 保证范围合法
C2 = min(max(C2,0),1);
end
