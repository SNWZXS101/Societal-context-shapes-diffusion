% Run_ranking_sensitivity_withX.m
clear; clc;

features_mat   = 'features_aug.mat';
cf_results_dir = 'results_cf';
outdir         = 'scores';

% 0) 逐波评分
WaveScores = compute_wave_scores(features_mat, cf_results_dir, ...
    'scenario','TGC_STRONG', ...
    'outdir',outdir, 'timestamp',false);

% 1) 省内聚合
ProvAgg = aggregate_province_scores(WaveScores, ...
    'nan_mode','exclude', 'outdir',outdir, 'timestamp',false, 'verbose',true);

% 2) 价值增量（纳入 X 固定效应）
ProvScores = residualize_value_added(WaveScores, ...
    'use_variant',true, ...
    'weights_col','w_tail', ...
    'w_RRI',0.4,'w_MEI',0.6, ...
    'features_mat',features_mat, ...
    'xvars',{'urban_rate','log_income_pc','log_transit_vol'}, ... % ← 按实际列名改
    'outdir',outdir, 'timestamp',true, 'verbose',true);

% 3) 进步指数（沿用同口径）
ProvProgress = compute_lpi(WaveScores, ProvScores, ...
    'features_mat',features_mat, ...
    'delta_ceiling',true, ...
    'slope_method','theilsen', ...
    'w_delta',0.5, 'w_slope',0.5, ...
    'outdir',outdir, 'timestamp',true, 'verbose',true);

disp('✔ 含X敏感性完成，查看 scores/ 目录输出。');
